async function actor(userId) {
  const sessionId = `session:${crypto.randomUUID()}`;
  const headers = { 'Content-Type': 'application/json', 'X-App-Session-Kind': 'demo', 'X-Demo-User-Id': userId, 'X-App-Session-Id': sessionId };
  const login = await originalFetch(`${base}/api/auth/session/login`, { method: 'POST', headers,
    body: JSON.stringify({ attemptId: `attempt:${crypto.randomUUID()}`, provider: 'demo' }) });
  assert.equal(login.status, 200); assert.equal((await login.json()).accepted, true);
  const params = new URLSearchParams({ chatId, userId, sessionKind: 'demo', sessionId });
  const socket = new WebSocket(`wss://localhost/api/activities/chats/ws?${params}`);
  const messages = [], waiters = [];
  socket.addEventListener('message', event => {
    const message = JSON.parse(event.data);
    const waiter = waiters.find(item => item.predicate(message));
    if (waiter) { waiters.splice(waiters.indexOf(waiter), 1); clearTimeout(waiter.timer); waiter.resolve(message); }
    else messages.push(message);
  });
  const take = predicate => {
    const index = messages.findIndex(predicate);
    if (index >= 0) return Promise.resolve(messages.splice(index, 1)[0]);
    return new Promise((resolve, reject) => {
      const waiter = { predicate, resolve, timer: setTimeout(() => { waiters.splice(waiters.indexOf(waiter), 1); reject(new Error('WebSocket event timeout')); }, 12_000) };
      waiters.push(waiter);
    });
  };
  await new Promise((resolve, reject) => { socket.addEventListener('open', resolve, { once: true }); socket.addEventListener('error', () => reject(new Error('Socket connection failed')), { once: true }); });
  const send = call => socket.send(JSON.stringify({ type: 'call', call }));
  send({ action: 'configuration' }); const config = await take(m => m.kind === 'configuration');
  assert.equal(config.available, true); assert.match(config.nodes[0].urls[0], /^stun:localhost:3478$/);
  assert.equal(config.nodes.length, 1);
  return { userId, socket, send, take, headers,
    close: async () => { socket.close(); await originalFetch(`${base}/api/auth/me/logout`, { method: 'POST', headers, body: JSON.stringify({ userId }) }); } };
}
const roster = (actor, count) => actor.take(m => m.kind === 'roster' && m.participants.length === count);
const mlsEvent = (actor, epoch) => actor.take(m => m.kind === 'mls' && m.epoch === epoch);

test('existing chat WebSocket carries MLS group signaling, rejects wrong authority, and elects a surviving coordinator', async () => {
  const clients = [], engines = [], callId = crypto.randomUUID(); let epoch = 0;
  try {
    for (const source of baseline.actors.slice(0, 3)) clients.push(await actor(source.id));
    const [alice, bob, carol] = clients;
    for (const client of clients) {
      engines.push(await ChatCallMls.create(callId, async bundle => {
        client.send({ action: 'commit', callId, epoch, data: JSON.stringify(bundle) });
        const ack = await client.take(m => m.kind === 'committed'); assert.equal(ack.epoch, epoch + 1); epoch = ack.epoch;
      }));
    }
    const [a, b, c] = engines;
    const join = (client, engine) => client.send({ action: 'join', callId, clientId: engine.clientId, bundle: engine.bundle(), nodeId: 'owned-0', video: false });
    join(alice, a); const one = await roster(alice, 1);
    await bob.take(m => m.kind === 'invite'); await carol.take(m => m.kind === 'invite');
    await a.reconcile(one.participants);
    join(bob, b); const two = await roster(alice, 2); const bobTwo = await roster(bob, 2);
    await a.reconcile(two.participants); await b.accept(JSON.parse((await mlsEvent(bob, 1)).data));
    const ciphertext = await a.encrypt({ offer: 'opaque SDP', callId });
    alice.send({ action: 'signal', callId, targetSessionId: bobTwo.selfSessionId, data: ciphertext });
    assert.equal((await b.decrypt((await bob.take(m => m.kind === 'signal')).data)).clientId, a.clientId);
    join(carol, c); const three = await roster(alice, 3); await roster(bob, 3); await roster(carol, 3);
    await a.reconcile(three.participants);
    await b.accept(JSON.parse((await mlsEvent(bob, 2)).data)); await c.accept(JSON.parse((await mlsEvent(carol, 2)).data));
    assert.equal(await a.verificationCode(), await c.verificationCode());
    for (const receiveVideo of [false, true]) {
      const payload = { chatId, callId, senderSessionId: one.selfSessionId, targetSessionId: bobTwo.selfSessionId, receiveVideo };
      alice.send({ action: 'signal', callId, targetSessionId: bobTwo.selfSessionId, data: await a.encrypt(payload) });
      assert.deepEqual(JSON.parse((await b.decrypt((await bob.take(m => m.kind === 'signal')).data)).plaintext), payload);
      await c.decrypt((await carol.take(m => m.kind === 'signal')).data);
    }
    assert.equal(three.participants[0].moderator, true);
    assert.equal(three.participants.find(p => p.sessionId === bobTwo.selfSessionId).moderator, false);
    bob.send({ action: 'mute', callId, targetSessionId: one.selfSessionId, muted: true });
    await bob.take(m => m.kind === 'error');
    alice.send({ action: 'mute', callId, targetSessionId: bobTwo.selfSessionId, muted: true });
    const muted = await bob.take(m => m.kind === 'roster' && m.participants.some(p => p.sessionId === bobTwo.selfSessionId && p.mutedByAdmin));
    assert.equal(muted.participants.find(p => p.sessionId === one.selfSessionId).mutedByAdmin, false);
    await alice.take(m => m.kind === 'roster' && m.participants.some(p => p.mutedByAdmin));
    await carol.take(m => m.kind === 'roster' && m.participants.some(p => p.mutedByAdmin));
    alice.send({ action: 'mute', callId, targetSessionId: bobTwo.selfSessionId, muted: false });
    for (const client of clients) await client.take(m => m.kind === 'roster' && m.participants.every(p => !p.mutedByAdmin));
    bob.send({ action: 'commit', callId, epoch, data: '{}' }); assert.equal((await bob.take(m => m.kind === 'error')).type, 'call');
    alice.send({ action: 'commit', callId, epoch: 0, data: '{}' }); await alice.take(m => m.kind === 'error');
    bob.send({ action: 'signal', callId: crypto.randomUUID(), targetSessionId: one.selfSessionId, data: 'opaque' }); await bob.take(m => m.kind === 'error');
    const groupSignal = await b.encrypt({ candidate: 'opaque ICE' });
    bob.send({ action: 'signal', callId, targetSessionId: one.selfSessionId, data: groupSignal });
    await a.decrypt((await alice.take(m => m.kind === 'signal')).data); await c.decrypt((await carol.take(m => m.kind === 'signal')).data);
    alice.socket.close();
    const survivors = await roster(bob, 2); await roster(carol, 2);
    assert.equal(survivors.participants[0].sessionId, bobTwo.selfSessionId);
    await b.reconcile(survivors.participants); await c.accept(JSON.parse((await mlsEvent(carol, 3)).data));
    assert.equal(await b.verificationCode(), await c.verificationCode());
    const next = await b.encrypt({ coordinator: 'bob' }); await c.decrypt(next); await assert.rejects(a.decrypt(next));
    bob.send({ action: 'leave', callId }); await roster(carol, 1);
    carol.send({ action: 'leave', callId }); await carol.take(m => m.kind === 'ended');
    console.log('Verified: own STUN config, 3-member MLS, opaque SDP/ICE, authority/epoch rejection, coordinator failover and room cleanup.');
  } finally { await Promise.allSettled(engines.map(engine => engine.destroy())); await Promise.allSettled(clients.map(client => client.close())); }
});

test('own STUN availability is pushed through the open chat WebSocket', async () => {
  const client = await actor(baseline.actors[0].id);
  try {
    execFileSync('docker', ['stop', '--time', '3', 'myscoutee-stun'], { stdio: 'ignore', timeout: 15000 });
    assert.equal((await client.take(m => m.kind === 'availability' && !m.available)).available, false);
    execFileSync('docker', ['start', 'myscoutee-stun'], { stdio: 'ignore', timeout: 15000 });
    assert.equal((await client.take(m => m.kind === 'availability' && m.available)).available, true);
  } finally {
    execFileSync('docker', ['start', 'myscoutee-stun'], { stdio: 'ignore', timeout: 15000 });
    await client.close();
  }
});
